export type PixelIconName = keyof typeof ICONS;
export const PIXEL_ICON_NAMES = Object.keys(ICONS) as PixelIconName[];

const FILL: Record<string, string> = {
  '#': 'currentColor',
  '+': 'var(--px-accent, var(--sub))',
  o: 'var(--px-light, var(--paper))',
};

/** Merges each row into runs of one character: [x, y, width, char]. */
function runs(rows: readonly string[]) {
  const out: Array<[number, number, number, string]> = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const char = row[x];
      let end = x;
      while (end < row.length && row[end] === char) end++;
      if (char in FILL) out.push([x, y, end - x, char]);
      x = end;
    }
  });
  return out;
}

const CACHE = new Map<PixelIconName, ReturnType<typeof runs>>();

export function PixelIcon({
  name,
  size = 32,
  className,
  label,
}: {
  name: PixelIconName;
  size?: number;
  className?: string;
  /** Only when the icon carries meaning on its own; otherwise it is hidden. */
  label?: string;
}) {
  let cells = CACHE.get(name);
  if (!cells) {
    cells = runs(ICONS[name]);
    CACHE.set(name, cells);
  }
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      className={`px-icon ${className ?? ''}`}
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
    >
      {cells.map(([x, y, w, char]) => (
        <rect key={`${x}-${y}`} x={x} y={y} width={w} height={1} fill={FILL[char]} />
      ))}
    </svg>
  );
}
