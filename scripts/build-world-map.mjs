/**
 * Generates src/data/worldMap.ts — a pre-projected SVG path per country.
 *
 * Doing this at build time rather than runtime means the page ships plain
 * path strings: no topojson, no d3-geo, no map library in the bundle, and
 * nothing to fetch. Re-run only if the country list or projection changes.
 *
 *   node scripts/build-world-map.mjs
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topology = require('world-atlas/countries-110m.json');

const WIDTH = 900;
const HEIGHT = 460;

const countries = feature(topology, topology.objects.countries).features
  // Antarctica adds a huge visual mass and no information here.
  .filter((f) => f.properties.name !== 'Antarctica');

const projection = geoNaturalEarth1().fitExtent(
  [
    [4, 4],
    [WIDTH - 4, HEIGHT - 4],
  ],
  { type: 'FeatureCollection', features: countries },
);

// 1 decimal place is well under a pixel at this size and roughly halves the
// generated file compared with the default precision.
const path = geoPath(projection).context(null);

const shapes = countries
  .map((f) => ({ name: f.properties.name, d: round(path(f)) }))
  .filter((c) => c.d)
  .sort((a, b) => a.name.localeCompare(b.name));

function round(d) {
  return d ? d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10)) : d;
}

const out = `// Generated by scripts/build-world-map.mjs — do not edit by hand.
// Natural Earth projection, ${WIDTH}x${HEIGHT}, Antarctica omitted.

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};

export type CountryShape = { name: string; d: string };

export const countryShapes: CountryShape[] = ${JSON.stringify(shapes)};
`;

writeFileSync('src/data/worldMap.ts', out);
console.log(`${shapes.length} countries, ${(out.length / 1024).toFixed(0)} KB`);
